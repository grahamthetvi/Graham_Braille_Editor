export function getCenterlineStrokes(text: string, fontSize: number): CenterlineResult {
  const scale = fontSize / 14;
  const spacing = 2 * scale;
  const strokes: CenterlineStroke[] = [];
  let currentX = 0;
  let maxY = 14;

  for (let i = 0; i < text.length; i++) {
    const char = text[i];
    const glyph = CENTERLINE_GLYPHS[char] || { width: 8, strokes: [] };
    const charW = glyph.width * scale;

    for (const strokePoints of glyph.strokes) {
      for (let j = 0; j < strokePoints.length - 1; j++) {
        const p1 = strokePoints[j];
        const p2 = strokePoints[j + 1];
        strokes.push({
          x1: currentX + p1[0] * scale,
          y1: p1[1] * scale,
          x2: currentX + p2[0] * scale,
          y2: p2[1] * scale
        });
        if (p1[1] > maxY) maxY = p1[1];
        if (p2[1] > maxY) maxY = p2[1];
      }
    }

    currentX += charW + spacing;
  }

  // Remove final spacing
  const totalW = currentX > 0 ? currentX - spacing : 0;
  const totalH = maxY * scale;

  return {
    width: totalW,
    height: totalH,
    strokes
  };
}
